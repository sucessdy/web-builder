
import { z } from "zod";

export const styleSchema = z
  .object({
    color: z.string().optional(),
    backgroundColor: z.string().optional(),
    fontSize: z.string().optional(),
    fontFamily: z.string().optional(),
    fontWeight: z.union([z.string(), z.number()]).optional(),
    lineHeight: z.union([z.string(), z.number()]).optional(),
    letterSpacing: z.string().optional(),
    textDecoration: z.enum(["none", "underline", "line-through"]).optional(),
    whiteSpace: z.enum(["normal", "nowrap", "pre-line", "pre-wrap"]).optional(),
    textAlign: z.enum(["left", "center", "right", "justify"]).optional(),
    alignItems: z.enum(["stretch", "flex-start", "center", "flex-end", "baseline"]).optional(),
    justifyContent: z.enum(["flex-start", "center", "flex-end", "space-between", "space-around", "space-evenly"]).optional(),
    flexWrap: z.enum(["nowrap", "wrap", "wrap-reverse"]).optional(),
    gridTemplateColumns: z.string().optional(),
    padding: z.string().optional(),
    margin: z.string().optional(),
    paddingTop: z.string().optional(),
    paddingRight: z.string().optional(),
    paddingBottom: z.string().optional(),
    paddingLeft: z.string().optional(),
    marginTop: z.string().optional(),
    marginRight: z.string().optional(),
    marginBottom: z.string().optional(),
    marginLeft: z.string().optional(),
    borderRadius: z.string().optional(),
    border: z.string().optional(),
    borderBottom: z.string().optional(),
    borderTop: z.string().optional(),
    borderWidth: z.string().optional(),
    borderStyle: z.enum(["none", "solid", "dashed", "dotted"]).optional(),
    borderColor: z.string().optional(),
    boxShadow: z.string().optional(),
    width: z.string().optional(),
    height: z.string().optional(),
    minWidth: z.string().optional(),
    maxWidth: z.string().optional(),
    minHeight: z.string().optional(),
    maxHeight: z.string().optional(),
    opacity: z.number().min(0).max(1).optional(),
    overflow: z.enum(["visible", "hidden", "auto"]).optional(),
    display: z.enum(["block", "flex", "grid", "inline-flex"]).optional(),
    flexDirection: z.enum(["row", "column"]).optional(),
    gap: z.string().optional(),
  })
  .strict();

export type NodeStyles = z.infer<typeof styleSchema>;
